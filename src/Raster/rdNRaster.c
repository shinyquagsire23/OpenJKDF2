// Shading axes for the DrawNGon template (RDN_SHADE).
#define RDN_FLAT    0   // no light table (full bright)
#define RDN_LIT     1   // one constant light level through the light table
#define RDN_GOURAUD 2   // per-pixel interpolated light level through the light table

// Per-vertex screen-space attributes for the face currently being rasterized. Same layout as
// rdZRaster's rdZVertex minus any depth role: oneOverW is kept only as the perspective divisor for
// IT texturing (there is no depth buffer in this family).
typedef struct rdNVertex
{
    flex_t sx, sy;      // screen position
    flex_t oneOverW;    // 1/w (perspective divisor for IT texturing)
    flex_t uOverW;      // texel-u / w   (perspective / IT)
    flex_t vOverW;      // texel-v / w   (perspective / IT)
    flex_t u, v;        // texel-u, texel-v (affine / AT — interpolated linearly in screen space)
    flex_t intensity;   // light level 0..63
} rdNVertex;

// State shared by every generated DrawNGon variant. The mode axes (solid / masked / translucent /
// affine / shade) are compile-time, baked into each variant by rdNRaster_ngon.h.
typedef struct rdNRasterState
{
    const uint8_t* pTexels;      // selected mip texels (textured variants)
    const uint8_t* pLightBase;   // colormap light table, or NULL for raw texels
    const uint8_t* pTransTable;  // colormap transparency LUT (translucent variants)
    int mip, mipW, mipH, mipStride;
    int solidColor;              // flat fill color (solid variants)
} rdNRasterState;

static flex_t rdNRaster_Clamp01(flex_t f)
{
    if (f < 0.0f) return 0.0f;
    if (f > 1.0f) return 1.0f;
    return f;
}

